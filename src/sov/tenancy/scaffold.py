"""tenants/<name>.yaml -> everything an authority needs outside its Helm release.

Writes deploy/generated/: a Vault policy, a Keycloak realm, the Grafana Loki data sources and an index.
`python scripts/scaffold.py --check` fails CI when the generated files are stale.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import yaml

from sov.config import ROOT

GENERATED = ROOT / "deploy" / "generated"
API_CLIENT = "inquiry-router-api"
PORTAL_CLIENT = "inquiry-portal"
ROLES = {"inquiry-router": "may route inquiries", "audit-reader": "may read release records and audit logs"}


def vault_policy(tenant: str) -> str:
    template = (ROOT / "infra" / "templates" / "vault-policy.hcl.tftpl").read_text(encoding="utf-8")
    return template.replace("${tenant}", tenant)


def keycloak_realm(spec: dict[str, Any]) -> dict[str, Any]:
    tenant = spec["name"]
    return {
        "realm": tenant,
        "displayName": spec["display_name"],
        "enabled": True,
        "sslRequired": "external",
        "accessTokenLifespan": 300,
        "bruteForceProtected": True,
        "roles": {"realm": [{"name": r, "description": d} for r, d in ROLES.items()]},
        "groups": [
            {"name": g["name"], "path": f"/{g['name']}", "realmRoles": g["roles"]} for g in spec["access"]["groups"]
        ],
        "clients": [
            {"clientId": API_CLIENT, "enabled": True, "bearerOnly": True, "publicClient": False},
            {
                "clientId": PORTAL_CLIENT,
                "enabled": True,
                "publicClient": True,
                "standardFlowEnabled": True,
                "directAccessGrantsEnabled": False,
                "redirectUris": [f"https://{tenant}.portal.example/*"],
                "webOrigins": [f"https://{tenant}.portal.example"],
                "attributes": {"pkce.code.challenge.method": "S256"},
                "protocolMappers": [
                    {
                        "name": "audience",
                        "protocol": "openid-connect",
                        "protocolMapper": "oidc-audience-mapper",
                        "config": {"included.client.audience": API_CLIENT, "access.token.claim": "true"},
                    }
                ],
            },
        ],
    }


def grafana_datasources(specs: dict[str, dict[str, Any]]) -> dict[str, Any]:
    return {
        "apiVersion": 1,
        "datasources": [
            {
                "name": f"Loki {s['display_name']}",
                "uid": f"loki-{name}",
                "type": "loki",
                "access": "proxy",
                "url": "http://loki-gateway.observability.svc",
                "jsonData": {"httpHeaderName1": "X-Scope-OrgID"},
                "secureJsonData": {"httpHeaderValue1": name},
            }
            for name, s in sorted(specs.items())
        ],
    }


def render(specs: dict[str, dict[str, Any]]) -> dict[Path, str]:
    files: dict[Path, str] = {}
    for name, spec in sorted(specs.items()):
        files[GENERATED / "vault" / f"{name}.hcl"] = vault_policy(name)
        files[GENERATED / "keycloak" / f"{name}-realm.json"] = (
            json.dumps(keycloak_realm(spec), indent=2, ensure_ascii=False) + "\n"
        )
    files[GENERATED / "grafana" / "datasources.yaml"] = (
        "# GENERATED by scripts/scaffold.py from tenants/*.yaml\n"
        + yaml.safe_dump(grafana_datasources(specs), sort_keys=False, allow_unicode=True)
    )
    files[GENERATED / "grafana" / "datasources-configmap.yaml"] = (
        "# GENERATED by scripts/scaffold.py\n"
        + yaml.safe_dump(
            {
                "apiVersion": "v1",
                "kind": "ConfigMap",
                "metadata": {
                    "name": "sov-loki-datasources",
                    "namespace": "observability",
                    "labels": {"grafana_datasource": "1"},
                },
                "data": {
                    "datasources.yaml": yaml.safe_dump(grafana_datasources(specs), sort_keys=False, allow_unicode=True)
                },
            },
            sort_keys=False,
            allow_unicode=True,
        )
    )
    files[GENERATED / "loki" / "overrides.yaml"] = (
        "# GENERATED by scripts/scaffold.py: per-authority log retention\n"
        + yaml.safe_dump(
            {
                "overrides": {
                    name: {"retention_period": f"{s['logs']['retention_days'] * 24}h"}
                    for name, s in sorted(specs.items())
                }
            },
            sort_keys=False,
        )
    )
    files[GENERATED / "index.json"] = (
        json.dumps(
            {
                name: {
                    "namespace": f"sov-{name}",
                    "vault_policy": f"vault/{name}.hcl",
                    "keycloak_realm": f"keycloak/{name}-realm.json",
                    "loki_tenant": name,
                }
                for name in sorted(specs)
            },
            indent=2,
        )
        + "\n"
    )
    return files
