"""Compile config/pii_rules.yaml and src/sov/pii/engine.lua into deploy/fluent-bit/redact.lua.

The output is generated and committed; `python scripts/gen_redactor.py --check` fails CI when it is stale.
"""

from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "deploy" / "fluent-bit" / "redact.lua"


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua_value(v: object) -> str:
    if isinstance(v, str):
        return lua_str(v)
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, list):
        return "{" + ", ".join(lua_value(x) for x in v) + "}"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k} = {lua_value(x)}" for k, x in v.items()) + "}"
    raise TypeError(type(v))


def build() -> str:
    spec = yaml.safe_load((ROOT / "config" / "pii_rules.yaml").read_text(encoding="utf-8"))
    engine = (ROOT / "src" / "sov" / "pii" / "engine.lua").read_text(encoding="utf-8")
    for rule in spec["rules"]:
        if "gazetteer" in rule:
            words = (ROOT / rule["gazetteer"]).read_text(encoding="utf-8").split("\n")
            rule["gazetteer"] = sorted({w.strip().lower() for w in words if w.strip() and not w.startswith("#")})
    rules = ",\n  ".join(lua_value(r) for r in spec["rules"])
    head = (
        "-- GENERATED by scripts/gen_redactor.py from config/pii_rules.yaml and src/sov/pii/engine.lua.\n"
        "-- Do not edit by hand.\n\n"
        f"PLACEHOLDER = {lua_str(spec['placeholder'])}\n\n"
        f"RULES = {{\n  {rules}\n}}\n\n"
    )
    return head + engine


CONFIGMAP = ROOT / "deploy" / "observability" / "fluent-bit-scripts" / "configmap.yaml"


def configmap(redact_lua: str) -> str:
    tenant_lua = (ROOT / "deploy" / "fluent-bit" / "tenant.lua").read_text(encoding="utf-8")
    doc = {
        "apiVersion": "v1",
        "kind": "ConfigMap",
        "metadata": {
            "name": "fluent-bit-scripts",
            "namespace": "observability",
            "labels": {"app.kubernetes.io/part-of": "sov-observability"},
        },
        "data": {"redact.lua": redact_lua, "tenant.lua": tenant_lua},
    }
    return "# GENERATED by scripts/gen_redactor.py\n" + yaml.safe_dump(
        doc, sort_keys=False, allow_unicode=True, width=1000
    )


def main() -> int:
    text = build()
    outputs = {OUT: text, CONFIGMAP: configmap(text)}
    if "--check" in sys.argv:
        stale = [p for p, t in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is stale: run python scripts/gen_redactor.py", file=sys.stderr)
        return 1 if stale else 0
    for p, t in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
